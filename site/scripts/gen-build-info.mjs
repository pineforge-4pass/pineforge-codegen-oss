// Writes lib/generated/build-info.ts (agreement draft flag, version, sha256)
// for the pages and the Functions, and publishes the trusted keyring at
// public/.well-known/pineforge-license-keys.json. Run by dev, build and check.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { AGREEMENT_MARKER, KEYRING_FILE, SITE, agreementInfo } from "./site-files.mjs";
import { parseKeyring } from "../lib/license.ts";

const info = await agreementInfo();
const genDir = join(SITE, "lib", "generated");
mkdirSync(genDir, { recursive: true });
writeFileSync(
  join(genDir, "build-info.ts"),
  `// GENERATED by scripts/gen-build-info.mjs from legal/commercial-license-agreement.md. Do not edit.
export const AGREEMENT_MARKER = ${JSON.stringify(AGREEMENT_MARKER)};
export const AGREEMENT_IS_DRAFT: boolean = ${info.isDraft};
export const AGREEMENT_VERSION = ${JSON.stringify(info.version)};
export const AGREEMENT_SHA256 = ${JSON.stringify(info.sha256)};
`,
);

const keyringText = readFileSync(KEYRING_FILE, "utf8");
const keyring = parseKeyring(keyringText); // throws on a malformed keyring
const wellKnown = join(SITE, "public", ".well-known");
mkdirSync(wellKnown, { recursive: true });
writeFileSync(join(wellKnown, "pineforge-license-keys.json"), JSON.stringify(keyring, null, 2) + "\n");

console.log(
  `build info: agreement ${info.version} sha256 ${info.sha256.slice(0, 12)}… draft=${info.isDraft}; keyring ${keyring.keys
    .map((k) => k.kid)
    .join(", ")}`,
);
